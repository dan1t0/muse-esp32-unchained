# provision.sh — flash a Muse gadget with nothing but a web-session cookie.
#
#   unchained_provision/provision.sh [--profile P] [--port PORT] [--no-flash]
#
# Reads secrets.txt (hatch_sess, wifi_ssid, wifi_password — see
# secrets.example.txt), builds the firmware with the web-session flag and the
# Wi-Fi baked in, flashes the board, feeds the cookie over serial
# (>web_cookie=, stored in NVS — sent once per flash) and verifies the boot
# reaches a registered, connected gadget. The cookie's value never reaches a
# log or the build's own config; the Wi-Fi password lands only in the
# gitignored build sdkconfig.
#
# Exit codes: 0 ok; 2 input/probe trouble; 3 muse.ai refused the cookie (expired
# — copy a fresh one); 4 board trouble; 1 anything else.
set -euo pipefail

DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO="$(cd "$DIR/.." && pwd)"
ESP="$REPO/esp32"
SECRET="$DIR/secrets.txt"
RUNTIME="$DIR/runtime.sdkconfig.defaults"
BLOG="/tmp/muse_provision_build.log"
VLOG="/tmp/muse_provision_verify.log"

PROFILE=""
PORT=""
NO_FLASH=0
while [ $# -ge 1 ]; do
  case "$1" in
    --profile) PROFILE="$2"; shift 2 ;;
    --port)    PORT="$2"; shift 2 ;;
    --no-flash) NO_FLASH=1; shift ;;
    *) echo "provision: unknown option $1" >&2; exit 1 ;;
  esac
done

die() { echo "provision: $*" >&2; exit "${2:-1}"; }
hint() { echo "provision: $*"; }

# ---- secrets ---------------------------------------------------------------
[ -f "$SECRET" ] || die "no $SECRET — cp secrets.example.txt secrets.txt and fill it in" 2

# Accept a bare value, a "hatch_sess=…" pair, or a whole "Cookie: …" header.
# Only the normalized value reaches the device; logs carry lengths only.
read_secrets() {
  python3 - "$SECRET" "$RUNTIME" "$DIR" <<'PY'
import os, re, sys
from urllib.parse import urlsplit

path, out_path, module_dir = sys.argv[1:]
sys.path.insert(0, module_dir)
from cookie_auth import normalize_cookie
lines = [l.strip() for l in open(path) if l.strip() and not l.strip().startswith("#")]

vals = {}
bare = []
for line in lines:
    m = re.match(r"(hatch_sess|wifi_ssid|wifi_password|tts_url|tts_voice|tts_model|tts_lang_code|tts_stream)\s*=\s*(.*)$", line, re.I)
    if m:
        key, value = m.group(1).lower(), m.group(2)
        # A cookie list can start with the session pair, without "Cookie:".
        # Preserve its name unless the value itself is a pasted header/pair.
        if (key == "hatch_sess" and ";" in value
                and not re.match(r"(?:cookie:|hatch_sess\s*=)", value, re.I)):
            value = line
        vals[key] = value
    else:
        bare.append(line)

cookie = vals.get("hatch_sess", "")
if not cookie and len(bare) == 1:
    cookie = bare[0]                      # exactly one bare line: treat as the cookie
if not cookie:
    sys.exit("error: no hatch_sess in secrets.txt")
try:
    cookie = normalize_cookie(cookie)
except ValueError as error:
    sys.exit(f"error: {error}")

ssid = vals.get("wifi_ssid", "")
pwd = vals.get("wifi_password", "")
if not ssid:
    sys.exit("error: no wifi_ssid in secrets.txt")
if len(ssid) > 32:
    sys.exit("error: the wifi_ssid is longer than 32 characters")
if len(pwd) > 64:
    sys.exit("error: the wifi_password is longer than 64 characters")
for key, v in (("wifi_ssid", ssid), ("wifi_password", pwd)):
    if '"' in v or "\\" in v:
        sys.exit(f"error: {key} cannot carry quotes or backslashes")

tts_url = vals.get("tts_url", "")
tts_voice = vals.get("tts_voice", "Federico")
tts_model = vals.get("tts_model", "tts-1")
tts_lang_code = vals.get("tts_lang_code", "")
tts_stream = vals.get("tts_stream", "false").lower()
if tts_lang_code and not re.fullmatch(r"[A-Za-z][A-Za-z0-9_-]{0,31}", tts_lang_code):
    sys.exit("error: invalid tts_lang_code")
if tts_stream not in ("true", "false"):
    sys.exit("error: tts_stream must be true or false")
if tts_url:
    url = urlsplit(tts_url)
    if url.scheme not in ("http", "https") or not url.hostname or url.username or url.password:
        sys.exit("error: tts_url must be an HTTP(S) endpoint without embedded credentials")
    for key, v, limit in (("tts_url", tts_url, 512), ("tts_voice", tts_voice, 128), ("tts_model", tts_model, 128)):
        if not v or len(v) > limit or any(ord(c) < 32 for c in v) or '"' in v or "\\" in v:
            sys.exit(f"error: invalid {key}")

# The runtime defaults: the web flag plus the baked Wi-Fi. 0600, gitignored.
with open(out_path, "w") as f:
    f.write("# generated by provision.sh from secrets.txt (gitignored)\n")
    f.write('CONFIG_HOMEHUB_WEB_SESSION=y\n')
    f.write(f'CONFIG_HOMEHUB_WIFI_SSID="{ssid}"\n')
    f.write(f'CONFIG_HOMEHUB_WIFI_PASSWORD="{pwd}"\n')
    f.write('CONFIG_MUSE_TTS_HTTP=' + ('y' if tts_url else 'n') + '\n')
    if tts_url:
        f.write(f'CONFIG_MUSE_TTS_URL="{tts_url}"\n')
        f.write(f'CONFIG_MUSE_TTS_VOICE="{tts_voice}"\n')
        f.write(f'CONFIG_MUSE_TTS_MODEL="{tts_model}"\n')
        f.write(f'CONFIG_MUSE_TTS_LANG_CODE="{tts_lang_code}"\n')
        f.write('CONFIG_MUSE_TTS_STREAM=' + ('y' if tts_stream == "true" else 'n') + '\n')
os.chmod(out_path, 0o600)

# The cookie file the serial feeder reads. 0600, gitignored.
cookie_path = os.path.join(os.path.dirname(out_path), ".hatch_sess")
with open(cookie_path, "w") as f:
    f.write(cookie)
os.chmod(cookie_path, 0o600)

hint = lambda s: print(f"provision: {s}")
hint(f"hatch_sess ({len(cookie)} chars) -> .hatch_sess; "
     f"ssid \"{ssid}\"; password {len(pwd)} chars -> runtime.sdkconfig.defaults")
hint(f"HTTP TTS {'enabled (' + tts_voice + ')' if tts_url else 'disabled'}")
PY
}
read_secrets || die "secrets" 2

# ---- the local cookie probe ---------------------------------------------------
# The same chain the gadget will run, from here: muse.ai taking the session
# (200) and returning the required VM, endpoint and both gateway tokens are
# necessary. A malformed 200 is refused before flashing, like a dead cookie.
hint "checking the cookie against muse.ai…"
RC=0
PROBE_OUT=$(python3 "$DIR/cookie_auth.py" "$DIR/.hatch_sess") || RC=$?
if [ "$RC" -ne 0 ]; then
  echo "$PROBE_OUT" >&2
  if [ "$RC" -eq 1 ]; then
    echo "provision: Muse refused the cookie — copy a fresh hatch_sess from a logged-in" >&2
    echo "provision: muse.ai tab (DevTools → Cookies → muse.ai) into secrets.txt and re-run." >&2
    exit 3
  fi
  die "the cookie probe failed before flashing" "$RC"
fi
echo "provision: $PROBE_OUT"

# ---- the ESP-IDF environment -------------------------------------------------
if ! command -v idf.py >/dev/null 2>&1; then
  for d in "${IDF_PATH:-}" "$HOME/esp/esp-idf-v6.0.1" "$HOME/esp/esp-idf-v6" "$HOME/esp/esp-idf"; do
    if [ -n "$d" ] && [ -f "$d/export.sh" ]; then
      # shellcheck disable=SC1091
      . "$d/export.sh" >/dev/null 2>&1
      break
    fi
  done
  command -v idf.py >/dev/null 2>&1 || die "idf.py not found; install ESP-IDF v6.0.1 first" 1
fi

# ---- the port ----------------------------------------------------------------
if [ -z "$PORT" ]; then
  FOUND=($(ls /dev/cu.usbmodem* /dev/cu.usbserial* /dev/ttyACM* /dev/ttyUSB* 2>/dev/null || true))
  [ "${#FOUND[@]}" -eq 1 ] || die "pass --port PORT; candidates: ${FOUND[*]:-none}" 4
  PORT="${FOUND[0]}"
fi
hint "port $PORT"

# ---- the board ---------------------------------------------------------------
# Profiles: the same overlays the repo's own builders pass. muse-175 is what
# the round 1.75 AMOLED takes on a 16 MB chip (the 1.75C overlay's 32 MB
# image gets refused by the bootloader — see REPORT.md).
profile_defaults() {
  case "$1" in
    muse-175)   echo "sdkconfig.defaults;devices/sdkconfig.muse;devices/sdkconfig.muse-waveshare-s3-175" ;;
    muse-175c)  echo "sdkconfig.defaults;devices/sdkconfig.muse;devices/sdkconfig.muse-waveshare-s3-175c" ;;
    muse-216)   echo "sdkconfig.defaults;devices/sdkconfig.muse;devices/sdkconfig.muse-waveshare-s3-216" ;;
    ideaspark)  echo "sdkconfig.defaults;devices/sdkconfig.ideaspark" ;;
    s3-devkit)  echo "sdkconfig.defaults;devices/sdkconfig.espressif-s3-devkitc-1" ;;
    c6-nopsram) echo "sdkconfig.defaults;devices/sdkconfig.c6-nopsram" ;;
    devkit)     echo "sdkconfig.defaults" ;;
    *) return 1 ;;
  esac
}
profile_target() {
  case "$1" in
    devkit) echo esp32c5 ;;
    c6-nopsram) echo esp32c6 ;;
    ideaspark) echo esp32 ;;
    *) echo esp32s3 ;;
  esac
}

if [ -z "$PROFILE" ]; then
  # The S3's chip-id prints no "Chip is" line (it warns and prints the MAC),
  # so take the first esp32 token anywhere in the output and normalize it to
  # an idf target name.
  CHIP=$(timeout 30 python -m esptool -p "$PORT" chip-id 2>/dev/null |
         grep -ao "ESP32-[A-Za-z0-9-]*" | head -1 |
         sed 's/ESP32-/esp32/; s/-//g' | tr 'A-Z' 'a-z' || true)
  [ -n "$CHIP" ] || die "couldn't reach the board on $PORT (hold BOOT and try again)" 4
  case "$CHIP" in esp32d0wd*) CHIP=esp32 ;; esac
  FLASH=$(timeout 45 python -m esptool -p "$PORT" flash-id 2>/dev/null | grep -ao "Detected flash size: [0-9]*MB" | grep -ao "[0-9]*MB" || true)
  # A running muse firmware names itself; the chip alone doesn't pick a UI
  # profile, so known muse boards win, then a chip fallback.
  NAME=$(cd "$ESP" && timeout 15 python3 tools/muse/chat.py --status 2>/dev/null |
         python3 -c "import json,sys
try: print(json.load(sys.stdin)['board'])    # the board's own name
except Exception: pass" || true)
  case "$NAME" in
    *"AMOLED-1.75C"*) PROFILE=muse-175c ;;
    *"AMOLED-1.75"*)  PROFILE=muse-175 ;;
    *"AMOLED-2.16"*)  PROFILE=muse-216 ;;
    *"Voice Preview"*) PROFILE=s3-devkit ;;
    *"Indicator"*)    PROFILE=s3-devkit ;;
    "")
      case "$CHIP" in
        esp32c5) PROFILE=devkit ;;
        esp32c6) PROFILE=c6-nopsram ;;
        esp32s3) PROFILE=s3-devkit ;;
        *) die "chip $CHIP has no default profile; pass --profile" 4 ;;
      esac ;;
    *) die "board \"$NAME\" has no profile here; pass --profile" 4 ;;
  esac
  hint "chip $CHIP, flash ${FLASH:-?}, board \"${NAME:-not running muse}\" -> profile $PROFILE"
else
  hint "profile $PROFILE (given)"
fi
profile_defaults "$PROFILE" >/dev/null || die "unknown profile $PROFILE" 4
TARGET=$(profile_target "$PROFILE")

# Guard the 32-vs-16 MB trap at the door: refuse an overlay whose image is
# bigger than the chip (the bootloader refuses the finished image far less
# politely — see REPORT.md).
if [ -n "${FLASH:-}" ]; then
  case "$PROFILE" in
    muse-175c) want=32 ;;
    muse-175|muse-216) want=16 ;;
    devkit|s3-devkit|c6-nopsram) want=8 ;;
  esac
  got=${FLASH%MB}
  if [ -n "${want:-}" ] && [ "$got" -lt "$want" ] 2>/dev/null; then
    die "chip has ${got} MB flash but $PROFILE builds a ${want} MB image; pick a smaller profile" 4
  fi
fi

# Reuse the repo's own per-profile build directories: a second provisioning
# of a known profile is then an incremental build.
BUILD="$ESP/build-$PROFILE"
DEFAULTS="$(profile_defaults "$PROFILE");$RUNTIME"

# Generated sdkconfig wins over defaults on subsequent runs. Synchronize only
# the settings managed by this script, preserving the board and user options.
python3 - "$BUILD/sdkconfig" "$RUNTIME" <<'PY'
from pathlib import Path
import os, re, sys, tempfile
config, runtime = map(Path, sys.argv[1:])
if config.exists():
    managed = dict(line.split("=", 1) for line in runtime.read_text().splitlines()
                   if line.startswith("CONFIG_"))
    lines = []
    for line in config.read_text().splitlines():
        match = re.match(r"(?:# )?(CONFIG_[A-Z0-9_]+)(?:=| is not set)", line)
        if not match or match.group(1) not in managed:
            lines.append(line)
    lines.extend(f"# {key} is not set" if value == "n" else f"{key}={value}"
                 for key, value in managed.items())
    fd, path = tempfile.mkstemp(dir=config.parent, prefix=".sdkconfig-")
    with os.fdopen(fd, "w") as f:
        f.write("\n".join(lines) + "\n")
    os.replace(path, config)
PY

hint "building $PROFILE (web session on, Wi-Fi baked)…"
if [ "$NO_FLASH" -eq 0 ]; then
  (cd "$ESP" && idf.py -p "$PORT" -B "$BUILD" -DIDF_TARGET="$TARGET" \
      -DSDKCONFIG="$BUILD/sdkconfig" \
      -DSDKCONFIG_DEFAULTS="$DEFAULTS" build flash) > "$BLOG" 2>&1 \
    || { tail -12 "$BLOG" >&2; die "build or flash failed — $BLOG" 1; }
else
  (cd "$ESP" && idf.py -B "$BUILD" -DIDF_TARGET="$TARGET" \
      -DSDKCONFIG="$BUILD/sdkconfig" \
      -DSDKCONFIG_DEFAULTS="$DEFAULTS" build) > "$BLOG" 2>&1 \
    || { tail -12 "$BLOG" >&2; die "build failed — $BLOG" 1; }
  hint "build ok (no-flash: skip flashing and the cookie)"
  exit 0
fi
grep -a "muse-gadget.bin binary size" "$BLOG" | tail -1 | sed 's/^/provision: /'

# ---- the cookie --------------------------------------------------------------
# Flashing leaves NVS alone, so a re-provision needs no re-send — but sending
# is idempotent (the gadget answers @web_cookie ok and restarts) and keeps
# secrets.txt the single source of truth. One restart, at a fresh boot.
hint "feeding the web cookie over serial…"
python3 "$DIR/send_cookie.py" "$PORT" "$DIR/.hatch_sess" || die "cookie not accepted" 1

# ---- verify ------------------------------------------------------------------
hint "watching the boot until the gadget is registered and connected (75 s)…"
timeout 95 python3 "$ESP/tools/muse/monitor.py" "$PORT" 75 > "$VLOG" 2>&1 || true

# verify_boot.py decides: a refused upgrade only counts when nothing connected
# after it (the firmware retries with a fresh mint), and a working session
# whose link.register ack is still pending passes with a warning.
VERDICT=0
python3 "$DIR/verify_boot.py" "$VLOG" 75 || VERDICT=$?
if [ "$VERDICT" -ne 0 ]; then
  if [ "$VERDICT" -eq 1 ]; then
    echo "provision: see $VLOG (tail:)" >&2
    grep -aE "link\.|E \(" "$VLOG" | tail -6 >&2
  fi
  exit "$VERDICT"
fi

# The status page over serial, as a final receipt.
cd "$ESP" && timeout 30 python3 tools/muse/chat.py --status 2>/dev/null |
  python3 -c "import json,sys
d = json.load(sys.stdin).get('device', {})
h = d.get('hatch', {}); l = d.get('link', {})
print(f\"provision: status  hatch={h.get('state')}  vm={h.get('vm','')[:8]}…  link={l.get('state')}\")" || true
